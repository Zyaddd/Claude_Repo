def esc(s):
    s = escape(s)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "res")
for folder, idx in (("values", 0), ("values-ar", 1)):
    os.makedirs(os.path.join(root, folder), exist_ok=True)
    with open(os.path.join(root, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by iptv/tools/strings.py -->\n<resources>\n')
        for k, v in S.items():
            f.write(f'    <string name="{k}">{esc(v[idx])}</string>\n')
        f.write("</resources>\n")
print(len(S), "strings")
